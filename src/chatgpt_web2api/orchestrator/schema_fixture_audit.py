"""Audit an installed Codex JSON-schema bundle against explicit JSON fixtures.

Only reads files generated by the trusted offline version/schema capture.
No app-server process is started; no authentication, network or inference.
The caller selects the exact target schema: no guessing from file names.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path, PurePosixPath

from jsonschema import validators
from referencing import Registry, Resource
from referencing.jsonschema import DRAFT202012

from .codex_readiness import _MAX_SCHEMA_FILES, _MAX_SCHEMA_TOTAL_BYTES
from .storage_hardening import reject_reparse_path


def _selected_relative(name: str) -> PurePosixPath:
    if (type(name) is not str or not name or "\\" in name
            or name.startswith("/") or "\x00" in name):
        raise ValueError("schema must be an explicit relative POSIX JSON path")
    relative = PurePosixPath(name)
    if (relative.suffix != ".json" or any(part in (".", "..") for part in relative.parts)
            or len(relative.parts) > 12 or len(name) > 512
            or str(relative) != name):
        raise ValueError("invalid relative schema path")
    return relative


def _digest(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def _read_json(path: Path, *, size_limit: int):
    reject_reparse_path(path, error_message="Codex schema contains reparse path")
    if not path.is_file() or path.is_symlink() or path.stat().st_size > size_limit:
        raise ValueError("missing, redirected or oversized JSON file")
    with path.open("r", encoding="utf-8") as handle:
        return json.load(handle)


def verified_bundle(root_value: str | Path) -> tuple[dict, dict[str, dict]]:
    """Verify every manifest hash; detect missing/extra JSON before validation."""
    root = Path(root_value).expanduser()
    reject_reparse_path(root, error_message="Codex schema root traverses reparse point")
    if not root.is_dir() or root.is_symlink():
        raise ValueError("generated schema root must be an existing directory")
    receipt_path = root / "offline-readiness.json"
    receipt = _read_json(receipt_path, size_limit=1024 * 1024)
    if (type(receipt) is not dict or receipt.get("installed_schema_inspected") is not True
            or type(receipt.get("codex_version")) is not str
            or type(receipt.get("codex_binary_sha256")) is not str
            or len(receipt["codex_binary_sha256"]) != 64):
        raise ValueError("invalid offline Codex schema receipt")
    entries = receipt.get("generated_json_schema")
    if type(entries) is not list or not 1 <= len(entries) <= _MAX_SCHEMA_FILES:
        raise ValueError("invalid schema receipt manifest length")
    declared = {}
    for item in entries:
        if type(item) is not dict or type(item.get("sha256")) is not str:
            raise ValueError("invalid schema manifest entry")
        relative = _selected_relative(item.get("path"))
        name = relative.as_posix()
        if name == "offline-readiness.json" or name in declared:
            raise ValueError("duplicate or reserved schema path")
        sha = item["sha256"]
        if len(sha) != 64 or any(c not in "0123456789abcdef" for c in sha):
            raise ValueError("invalid schema checksum")
        declared[name] = sha
    seen = {}
    total = 0
    for path in root.rglob("*.json"):
        relative = path.relative_to(root).as_posix()
        if relative == "offline-readiness.json":
            continue
        if relative not in declared or len(seen) >= _MAX_SCHEMA_FILES:
            raise ValueError("unexpected or excessive schema file")
        reject_reparse_path(path, error_message="generated schema traverses reparse path")
        if not path.is_file() or path.is_symlink():
            raise ValueError("generated schema is not a regular file")
        total += path.stat().st_size
        if path.stat().st_size > 25_000_000 or total > _MAX_SCHEMA_TOTAL_BYTES:
            raise ValueError("schema bundle exceeds bounded size")
        if _digest(path) != declared[relative]:
            raise ValueError("Codex JSON-schema checksum changed since capture")
        content = _read_json(path, size_limit=25_000_000)
        if type(content) is not dict:
            raise ValueError("JSON Schema file is not an object")
        seen[relative] = content
    if set(seen) != set(declared):
        raise ValueError("missing schema files from offline capture")
    return receipt, seen


def audit_fixture(
    root_value: str | Path, schema_name: str, fixture_file: str | Path,
) -> dict:
    """Reject schema-incompatible JSON; never migrate or modify the fixture."""
    receipt, schemas = verified_bundle(root_value)
    name = _selected_relative(schema_name).as_posix()
    if name not in schemas:
        raise ValueError("selected schema was not captured")
    fixture_path = Path(fixture_file).expanduser()
    instance = _read_json(fixture_path, size_limit=1024 * 1024)
    root = Path(root_value).expanduser().resolve()
    resources = []
    for relative, document in schemas.items():
        resource = Resource.from_contents(document, default_specification=DRAFT202012)
        resources.append(((root / relative).as_uri(), resource))
        schema_id = document.get("$id")
        if isinstance(schema_id, str) and schema_id:
            resources.append((schema_id, resource))
    registry = Registry().with_resources(resources)
    schema = schemas[name]
    validator_type = validators.validator_for(schema)
    validator_type.check_schema(schema)
    # Registry provides only captured, in-memory resources. No remote URI fetch.
    validator = validator_type(schema, registry=registry)
    try:
        errors = list(validator.iter_errors(instance))
    except Exception as exc:
        raise ValueError("schema reference was not resolvable inside captured bundle") from exc
    error_paths = sorted(
        {"/" + "/".join(str(x) for x in error.absolute_path) for error in errors}
    )
    return {
        "codex_version": receipt["codex_version"],
        "schema": name,
        "valid": not bool(errors),
        "error_count": len(errors),
        "error_paths": error_paths[:20],
        "provider_contacted": False,
        "live_send_permitted": False,
    }
